-- 1. charts.id becomes 32 random hex digits; the old integer id stays as charts.number_id,
--    so existing charts keep their numbers and new ones continue after the highest.
-- 2. Every chart_id reference (likes, comments, plays, bookmarks, parent chart) follows.
-- 3. A content-addressed files table; charts point at it. The legacy per-revision keys stay
--    nullable until lib/legacy-files.ts has moved every chart, and are dropped in a later migration.

CREATE TABLE "files" (
	"id" bigserial PRIMARY KEY NOT NULL,
	"storage_key" text NOT NULL,
	"sha256" text NOT NULL,
	"extension" text NOT NULL,
	"byte_size" bigint NOT NULL,
	"content_type" text NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "files_storageKey_unique" UNIQUE("storage_key"),
	CONSTRAINT "files_sha256_check" CHECK ("files"."sha256" ~ '^[0-9a-f]{64}$'),
	CONSTRAINT "files_storage_key_check" CHECK ("files"."storage_key" = "files"."sha256" || '.' || "files"."extension")
);
